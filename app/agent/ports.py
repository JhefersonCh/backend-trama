from typing import Any, Protocol
from uuid import UUID


class AgentRepo(Protocol):
    async def session_exists(self, sid: UUID) -> bool: ...
    async def get_case(self, sid: UUID) -> dict[str, Any] | None: ...
    async def ensure_case(self, sid: UUID) -> dict[str, Any]: ...
    async def active_facts(self, sid: UUID) -> list[dict[str, Any]]: ...
    async def upsert_fact(
        self, sid: UUID, key: str, value: Any, source: str, certainty: float,
        evidence_ref: UUID | None = None, turn_id: str | None = None,
    ) -> dict[str, Any]: ...  # fmt: skip
    async def get_hypotheses(self, sid: UUID) -> list[dict[str, Any]]: ...
    async def replace_hypotheses(self, sid: UUID, items: list[dict[str, Any]]) -> None: ...
    async def append_trace(
        self, sid: UUID, phase: str, *, facts_used: list, rules_fired: list[str], hypotheses: list,
        action: str | None = None, autonomy: str | None = None, reason: str | None = None, turn_id: str | None = None,
    ) -> None: ...  # fmt: skip
    async def list_trace(self, sid: UUID, limit: int = 50) -> list[dict[str, Any]]: ...
    async def latest_trace(self, sid: UUID, phase: str) -> dict[str, Any] | None: ...
    async def get_setting(self, key: str) -> Any | None: ...
    async def actions_taken(self, sid: UUID) -> list[str]: ...
    async def update_case(
        self, sid: UUID, *, state: str | None = None, verified: bool | None = None, ticket_number: str | None = None
    ) -> None: ...
    # rule sets
    async def active_rule_set(self) -> dict[str, Any] | None: ...
    async def list_rule_sets(self) -> list[dict[str, Any]]: ...
    async def get_rule_set(self, version: int) -> dict[str, Any] | None: ...
    async def create_rule_set(self, content_yaml: str) -> dict[str, Any]: ...
    async def activate_rule_set(self, version: int) -> None: ...
