from __future__ import annotations

from collections.abc import Awaitable, Callable
from datetime import datetime
from typing import Any, Protocol

KINDS = ("followup", "sla_watch", "outage_watch", "remeasure", "step_timer")


class NotificationHub(Protocol):
    def register(self, session_id: str, send: Callable[[dict], Awaitable[None]]) -> None: ...
    def unregister(self, session_id: str) -> None: ...


class ProactivePort(Protocol):
    async def schedule(
        self,
        kind: str,
        *,
        session_id: str | None = None,
        ticket_id: str | None = None,
        run_at: datetime,
        payload: dict | None = None,
    ) -> str: ...
    async def ack(self, notification_id: str) -> None: ...

    hub: NotificationHub


class ProactiveStore(Protocol):
    """Persistence used by hub, worker and service (Pg impl in repo.py, fake in tests)."""

    async def insert_job(
        self, kind: str, session_id: str | None, ticket_id: str | None, run_at: datetime, payload: dict
    ) -> str: ...
    async def claim_due(self, limit: int) -> list[dict[str, Any]]: ...
    async def finish_job(self, job_id: str, status: str, error: str | None, run_at: datetime | None = None) -> None: ...
    async def reset_running(self) -> None: ...
    async def list_jobs(self, status: str | None, limit: int) -> list[dict[str, Any]]: ...
    async def insert_notification(self, session_id: str, text: str, kind: str) -> str: ...
    async def undelivered(self, session_id: str) -> list[dict[str, Any]]: ...
    async def mark_delivered(self, notification_id: str) -> None: ...
    async def list_notifications(self, session_id: str, limit: int) -> list[dict[str, Any]]: ...
    async def ticket_info(self, ticket_id: str) -> dict[str, Any] | None: ...
    async def open_ticket_for_session(self, session_id: str) -> dict[str, Any] | None: ...
    async def add_ticket_event(self, ticket_id: str, event_type: str, new: dict | None, details: str) -> None: ...
